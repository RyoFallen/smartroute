package com.smartroute.traveler.ui.theme

import androidx.compose.ui.graphics.Color
import kotlin.math.pow

private fun channel(c: Float): Double {
    val v = c.toDouble()
    return if (v <= 0.03928) v / 12.92 else ((v + 0.055) / 1.055).pow(2.4)
}

private fun luminance(c: Color): Double = 0.2126 * channel(c.red) + 0.7152 * channel(c.green) + 0.0722 * channel(c.blue)

/** WCAG 2.x contrast ratio between two colours (alpha is ignored; composite with [over] first). */
fun contrastRatio(
    a: Color,
    b: Color,
): Double {
    val la = luminance(a)
    val lb = luminance(b)
    return (maxOf(la, lb) + 0.05) / (minOf(la, lb) + 0.05)
}

/** Alpha-composites this colour over an opaque [background]; the result is opaque. */
fun Color.over(background: Color): Color {
    val a = alpha
    return Color(
        red = red * a + background.red * (1 - a),
        green = green * a + background.green * (1 - a),
        blue = blue * a + background.blue * (1 - a),
        alpha = 1f,
    )
}
