/**
 * Writes the benchmark operator's fare checklist, docs/benchmark/fare-checklist.md
 * (#36): exactly which (origin, destination, date) RecordedFares the frozen
 * scenarios need, grouped by directed pair with each pair's date range.
 *
 * Run by hand (never CI):
 *   pnpm --filter @smartroute/backend exec tsx scripts/benchmark/fare-checklist.ts
 *   ... --check   to fail if the committed checklist is out of date
 *
 * Before rendering it redraws the scenarios from the committed seed and refuses
 * a file that does not match, so a hand edit to scenarios.json cannot pass as
 * the seeded draw. Output goes through Prettier for the same reason as
 * scripts/attraction-data-coverage.ts: `docs/**` must be Prettier-clean, and
 * `--check` must compare like with like.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import {
  ScenarioFile,
  drawScenarios,
  fareChecklist,
  type BenchmarkScenario,
  type FareChecklist,
} from '../../src/services/benchmark/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const docs = path.resolve(here, '../../../../docs/benchmark');
const scenariosPath = path.join(docs, 'scenarios.json');
const notePath = path.join(docs, 'fare-checklist.md');

const file = ScenarioFile.parse(JSON.parse(readFileSync(scenariosPath, 'utf8')));
if (!isDeepStrictEqual(file.scenarios, drawScenarios(file.seed))) {
  console.error(
    `scenarios.json does not match what seed ${file.seed} draws — it was edited by hand.`,
  );
  process.exit(1);
}

/**
 * The day the last flight leaves, read off the scenario's own checklist rather
 * than re-derived here: every order's last leg flies into the end city on the
 * same day, so the latest date into it is that day, and the optimizer's single
 * leg-dating rule stays the only one (ADR-0006).
 */
function lastFlight(s: BenchmarkScenario): string {
  return fareChecklist([s])
    .pairs.filter((p) => p.destination === s.endCity)
    .map((p) => p.latest)
    .sort()
    .at(-1)!;
}

function render(scenarios: BenchmarkScenario[], seed: number, checklist: FareChecklist): string {
  const allDates = checklist.pairs.flatMap((p) => p.dates).sort();
  const months = [...new Set(allDates.map((d) => d.slice(0, 7)))];
  const out: string[] = [];

  out.push('# Benchmark fare checklist');
  out.push('');
  out.push(
    '_Generated by `scripts/benchmark/fare-checklist.ts` from the frozen',
    '[`scenarios.json`](scenarios.json) — do not edit by hand._',
  );
  out.push('');
  out.push(
    `The ${scenarios.length} BenchmarkScenarios drawn from seed **${seed}** need **${checklist.totalFares}**`,
    `distinct RecordedFares over **${checklist.pairs.length}** directed city pairs, departing between`,
    `**${allDates[0]}** and **${allDates.at(-1)}** (months: ${months.join(', ')}). Each is the price`,
    "the optimizer would ask for with the scenario's origin and end city pinned, so a CaptureSession",
    'that records every row below can price every order of every scenario. A fare the date grid shows',
    'no price for is still recorded, explicitly, as "no fare".',
  );
  out.push('');

  out.push('## Scenarios');
  out.push('');
  out.push(
    '| ID | Visited | Origin | Visited cities (CityStay days) | End | Departs | Last flight |',
  );
  out.push(
    '| -- | ------: | ------ | ------------------------------ | --- | ------- | ----------- |',
  );
  for (const s of scenarios) {
    const visited = s.visited.map((v) => `${v.city} ${v.stayDays}`).join(', ');
    out.push(
      `| ${s.id} | ${s.visited.length} | ${s.origin} | ${visited} | ${s.endCity} | ${s.departDate} | ${lastFlight(s)} |`,
    );
  }
  out.push('');

  out.push('## Date grids by pair');
  out.push('');
  out.push('| Pair | Fares | Earliest | Latest |');
  out.push('| ---- | ----: | -------- | ------ |');
  for (const p of checklist.pairs) {
    out.push(
      `| ${p.origin} → ${p.destination} | ${p.dates.length} | ${p.earliest} | ${p.latest} |`,
    );
  }
  out.push('');

  out.push('## Every fare needed');
  out.push('');
  for (const p of checklist.pairs) {
    out.push(`- **${p.origin} → ${p.destination}** (${p.dates.length}): ${p.dates.join(', ')}`);
  }
  out.push('');

  return out.join('\n');
}

const checklist = fareChecklist(file.scenarios);
const note = await prettier.format(render(file.scenarios, file.seed, checklist), {
  ...(await prettier.resolveConfig(notePath)),
  parser: 'markdown',
});

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(notePath, 'utf8');
  } catch {
    // A missing checklist is just an out-of-date one.
  }
  if (existing !== note) {
    console.error(`${path.relative(process.cwd(), notePath)} is out of date — regenerate it.`);
    process.exit(1);
  }
  console.log('Fare checklist is up to date.');
} else {
  writeFileSync(notePath, note);
  console.log(
    `Wrote ${path.relative(process.cwd(), notePath)}: ${checklist.totalFares} fares over ` +
      `${checklist.pairs.length} pairs.`,
  );
}
